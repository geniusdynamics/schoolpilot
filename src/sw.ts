/**
 * Service Worker
 * 
 * Main service worker for SchoolPilot3 PWA.
 * Handles caching, background sync, and push notifications.
 */

/// <reference lib="webworker" />

declare const self: ServiceWorkerGlobalScope & {
  __WB_MANIFEST: Array<{ url: string; revision: string | null }>;
};

import { precacheAndRoute, cleanupOutdatedCaches } from 'workbox-precaching';
import { registerRoute } from 'workbox-routing';

import { 
  NetworkFirst, 
  CacheFirst, 
  StaleWhileRevalidate,
  NetworkOnly
} from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';
import { BackgroundSyncPlugin } from 'workbox-background-sync';

// ============================================================================
// Precaching
// ============================================================================

// Precache files generated by the build process
precacheAndRoute(self.__WB_MANIFEST || []);

// Clean up old caches
cleanupOutdatedCaches();

// ============================================================================
// Routing Strategies
// ============================================================================

// Navigation routes - Network first for HTML
type WorkboxStrategy = { handle: (options: { request: Request; url: URL }) => Promise<Response> };

const navigationStrategy = new NetworkFirst({
  cacheName: 'pages-cache',
  plugins: [
    new CacheableResponsePlugin({
      statuses: [200],
    }),
  ],
});

registerRoute(
  ({ request }) => request.mode === 'navigate',
  navigationStrategy as WorkboxStrategy
);

// API routes - Network first with background sync
const apiStrategy = new NetworkFirst({
  cacheName: 'api-cache',
  plugins: [
    new CacheableResponsePlugin({
      statuses: [0, 200],
    }),
    new ExpirationPlugin({
      maxEntries: 100,
      maxAgeSeconds: 5 * 60, // 5 minutes
    }),
  ],
});

registerRoute(
  ({ url }) => url.pathname.startsWith('/api/'),
  apiStrategy as WorkboxStrategy
);

// Static assets - Cache first
const assetStrategy = new CacheFirst({
  cacheName: 'assets-cache',
  plugins: [
    new CacheableResponsePlugin({
      statuses: [0, 200],
    }),
    new ExpirationPlugin({
      maxEntries: 200,
      maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
    }),
  ],
});

registerRoute(
  ({ request }) => 
    request.destination === 'style' ||
    request.destination === 'script' ||
    request.destination === 'font',
  assetStrategy as WorkboxStrategy
);

// Images - Stale while revalidate
const imageStrategy = new StaleWhileRevalidate({
  cacheName: 'images-cache',
  plugins: [
    new CacheableResponsePlugin({
      statuses: [0, 200],
    }),
    new ExpirationPlugin({
      maxEntries: 100,
      maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
    }),
  ],
});

registerRoute(
  ({ request }) => request.destination === 'image',
  imageStrategy as WorkboxStrategy
);

// ============================================================================
// Background Sync
// ============================================================================

const bgSyncPlugin = new BackgroundSyncPlugin('sync-queue', {
  maxRetentionTime: 24 * 60, // 24 hours
  onSync: async ({ queue }) => {
    let entry;
    while ((entry = await queue.shiftRequest())) {
      try {
        await fetch(entry.request);
        console.log('[SW] Background sync successful:', entry.request.url);
      } catch (error) {
        console.error('[SW] Background sync failed:', error);
        await queue.unshiftRequest(entry);
        throw error;
      }
    }
  },
});

// Apply background sync to API mutations
registerRoute(
  ({ url, request }) => 
    url.pathname.startsWith('/api/') &&
    ['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method),
  new NetworkOnly({
    plugins: [bgSyncPlugin],
  }) as WorkboxStrategy
);

// ============================================================================
// Event Handlers
// ============================================================================

// Install event
self.addEventListener('install', () => {
  console.log('[SW] Installing...');
});

// Activate event
self.addEventListener('activate', (event) => {
  console.log('[SW] Activating...');
  event.waitUntil(self.clients.claim());
});

// Sync event
self.addEventListener('sync', (event) => {
  console.log('[SW] Sync event:', event.tag);
  
  if (event.tag === 'background-sync') {
    event.waitUntil(
      (async () => {
        // Notify clients to trigger sync
        const clients = await self.clients.matchAll({ type: 'window' });
        for (const client of clients) {
          client.postMessage({ type: 'trigger-sync' });
        }
      })()
    );
  }
});

// Push event
self.addEventListener('push', (event) => {
  console.log('[SW] Push event received');
  
  const data = event.data?.json() || {};
  const title = data.title || 'SchoolPilot';
  const options: NotificationOptions = {
    body: data.body || 'You have a new notification',
    icon: '/icons/icon-192x192.png',
    badge: '/icons/icon-72x72.png',
    tag: data.tag || 'default',
    requireInteraction: data.requireInteraction || false,
    actions: data.actions || [],
    data: data.data || {},
  };

  event.waitUntil(
    self.registration.showNotification(title, options)
  );
});

// Notification click event
self.addEventListener('notificationclick', (event) => {
  console.log('[SW] Notification clicked:', event.notification.tag);
  
  event.notification.close();
  
  const notificationData = event.notification.data;
  let url = '/';
  
  if (notificationData?.url) {
    url = notificationData.url;
  } else if (event.action) {
    // Handle action buttons
    switch (event.action) {
      case 'view':
        url = notificationData?.viewUrl || '/';
        break;
      case 'dismiss':
        return;
      default:
        url = '/';
    }
  }

  event.waitUntil(
    self.clients.matchAll({ type: 'window' }).then((clients) => {
      // Focus existing window if open
      for (const client of clients) {
        if (client.url === url && 'focus' in client) {
          return client.focus();
        }
      }
      // Open new window
      if (self.clients.openWindow) {
        return self.clients.openWindow(url);
      }
    })
  );
});

// Message event (from client)
self.addEventListener('message', (event) => {
  const { type } = event.data;

  switch (type) {
    case 'skip-waiting':
      self.skipWaiting();
      break;

    case 'get-version':
      event.source?.postMessage({
        type: 'version',
        version: '3.0.0',
      });
      break;

    case 'clear-cache':
      event.waitUntil(
        caches.keys().then((cacheNames) => {
          return Promise.all(
            cacheNames.map((cacheName) => caches.delete(cacheName))
          );
        })
      );
      break;

    default:
      console.log('[SW] Unknown message:', type);
  }
});

// Fetch event (for custom handling)
self.addEventListener('fetch', () => {
  // Let Workbox handle most requests
  // Custom handling can be added here if needed
});

// ============================================================================
// Periodic Background Sync
// ============================================================================

self.addEventListener('periodicsync', (event) => {
  if (event.tag === 'schoolpilot-sync') {
    event.waitUntil(
      (async () => {
        console.log('[SW] Periodic sync triggered');
        
        // Notify clients
        const clients = await self.clients.matchAll({ type: 'window' });
        for (const client of clients) {
          client.postMessage({ type: 'periodic-sync' });
        }
      })()
    );
  }
});

console.log('[SW] Service worker loaded');
