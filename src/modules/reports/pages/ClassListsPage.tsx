// ABOUTME: Class lists: the canonical roster of the year, class and stream the shared scope selects,
// ABOUTME: with admission number, name, gender and the learning areas the year's teaching groups name.

import React, { useState, useMemo, useCallback, useEffect, useRef } from 'react';
import { useTranslation } from 'react-i18next';

import Card from '@/components/ui/Card';
import Button from '@/components/ui/Button';
import { DataGrid, type DataGridColumn } from '@/components/ui/data';
import SchoolLetterhead from '@/components/SchoolLetterhead';
import { PrinterIcon } from '@/components/ui/icons';
import { AcademicScopeFilterBar, useAcademicScope } from '@/academic-scope';
import Spinner from '@/components/ui/Spinner';

import { CanonicalRepositoryProvider } from '../data/canonicalRepository';
import { useCanonicalReportData, type ReportStudent } from '../data/useCanonicalReportData';
import { selectClassRoster } from '../data/rosterFilters';

export const ClassListsPageContent: React.FC = () => {
  const { t } = useTranslation('reports');
  const academicScope = useAcademicScope();
  const { scope } = academicScope;
  const { students, isLoading: loading } = useCanonicalReportData({
    academicYearId: scope.effective.yearId,
  });

  const [roster, setRoster] = useState<ReportStudent[] | null>(null);
  const autoGenerated = useRef(false);

  const generateRoster = useCallback(() => {
    setRoster(
      selectClassRoster(students ?? [], scope.effective.levelId, scope.effective.classGroupId)
    );
  }, [students, scope.effective.levelId, scope.effective.classGroupId]);

  const scopeReady = scope.years.length === 0 || scope.effective.yearId !== '';

  useEffect(() => {
    if (loading || !scopeReady || autoGenerated.current) return;
    autoGenerated.current = true;
    generateRoster();
  }, [loading, scopeReady, generateRoster]);

  const columns = useMemo<DataGridColumn<ReportStudent>[]>(
    () => [
      { header: 'Adm No', key: 'admission_no' },
      {
        header: 'Student Name',
        key: 'display_name',
        render: (_value, item) => `${item.first_name} ${item.last_name}`,
      },
      { header: 'Gender', key: 'gender' },
      {
        header: 'Class',
        key: 'classLabel',
        render: (_value, item) => item.classLabel ?? '-',
      },
      {
        header: 'Stream',
        key: 'streamName',
        render: (_value, item) => item.streamName ?? '-',
      },
      {
        header: 'Learning Areas',
        key: 'learningAreaNames',
        render: (_value, item) => (item.learningAreaNames.length > 0 ? item.learningAreaNames.join(', ') : '-'),
      },
    ],
    []
  );

  const isLoadingPage = loading || !scopeReady;
  const reportTitle = scope.year
    ? `${t('classListsPage.title', 'Class Lists')} · ${scope.year.name}`
    : t('classListsPage.title', 'Class Lists');
  const emptyState =
    (students ?? []).length === 0
      ? t('classListsPage.noStudentsInYear', 'No learners are on the roll for this school year.')
      : t(
          'classListsPage.noStudentsForScope',
          'No learners match the selected year, class and stream.'
        );

  return (
    <div className="space-y-3 pb-8">
      <Card
        title={t('classListsPage.title', 'Class Lists')}
        info={t('classListsPage.description', 'Learners of the selected year, class and stream.')}
      >
        <div className="p-4 border-b mb-4 bg-surface-muted rounded-md print:hidden">
          <AcademicScopeFilterBar scope={academicScope}>
            <Button onClick={generateRoster} disabled={isLoadingPage} className="h-10">
              {t('classListsPage.generateReport', 'Generate Report')}
            </Button>
          </AcademicScopeFilterBar>
        </div>

        {isLoadingPage || roster === null ? (
          <div className="flex justify-center items-center py-10">
            <Spinner size="lg" />
            <span className="ml-2">{t('classListsPage.loadingData', 'Loading data...')}</span>
          </div>
        ) : (
          <>
            <div className="flex justify-end mb-4 print:hidden">
              <Button
                variant="outline"
                leftIcon={<PrinterIcon className="h-4 w-4" />}
                onClick={() => window.print()}
              >
                {t('classListsPage.print', 'Print')}
              </Button>
            </div>
            <SchoolLetterhead title={reportTitle} />
            <DataGrid columns={columns} data={roster} loading={false} emptyState={emptyState} />
          </>
        )}
      </Card>
    </div>
  );
};

const ClassListsPage: React.FC = () => (
  <CanonicalRepositoryProvider>
    <div className="space-y-3">
      <ClassListsPageContent />
    </div>
  </CanonicalRepositoryProvider>
);

export default ClassListsPage;
