// ABOUTME: The student masterlist: every learner placed in the year, class and stream the shared scope
// ABOUTME: selects, filtered further by status and gender when the report is generated.

import React, { useState, useMemo, useCallback, useEffect, useRef } from 'react';
import Card from '@/components/ui/Card';

import { CanonicalRepositoryProvider } from '../data/canonicalRepository';
import { useCanonicalReportData } from '../data/useCanonicalReportData';
import Spinner from '@/components/ui/Spinner';
import { DataGrid, type DataGridColumn } from '@/components/ui/data';
import Select from '@/components/ui/Select';
import Button from '@/components/ui/Button';
import SchoolLetterhead from '@/components/SchoolLetterhead';
import { AcademicScopeFilterBar, useAcademicScope } from '@/academic-scope';

import { useTranslation } from 'react-i18next';
import { PersonGender, StudentStatus } from '@/core/types';
import type { ReportStudent } from '../data/useCanonicalReportData';
import { filterMasterlist } from '../data/rosterFilters';

export const StudentMasterlistPageContent: React.FC = () => {
  const academicScope = useAcademicScope();
  const { scope } = academicScope;
  const { students, isLoading: loading } = useCanonicalReportData({
    academicYearId: scope.effective.yearId,
  });
  const { t } = useTranslation('reports');

  const [selectedStatus, setSelectedStatus] = useState<StudentStatus | ''>('');
  const [selectedGender, setSelectedGender] = useState<PersonGender | ''>('');
  const [generatedStudents, setGeneratedStudents] = useState<ReportStudent[] | null>(null);
  const autoGenerated = useRef(false);

  const generateReport = useCallback(() => {
    setGeneratedStudents(
      filterMasterlist(students ?? [], {
        levelId: scope.effective.levelId,
        classGroupId: scope.effective.classGroupId,
        status: selectedStatus,
        gender: selectedGender,
      })
    );
  }, [students, scope.effective.levelId, scope.effective.classGroupId, selectedStatus, selectedGender]);

  // A year row must exist before the default scope can resolve; a school with no calendar still
  // gets its learners, placed nowhere, rather than an endless spinner.
  const scopeReady = scope.years.length === 0 || scope.effective.yearId !== '';

  // The first report is the default scope once its rows are loaded; afterwards the filters apply
  // only when Generate is pressed, so the table never changes under a reader's eyes.
  useEffect(() => {
    if (loading || !scopeReady || autoGenerated.current) return;
    autoGenerated.current = true;
    generateReport();
  }, [loading, scopeReady, generateReport]);

  const columns = useMemo<DataGridColumn<ReportStudent>[]>(
    () => [
      { header: 'Adm No', key: 'admission_no' },
      {
        header: 'Student Name',
        key: 'display_name',
        render: (_value, item) => `${item.first_name} ${item.last_name}`,
      },
      { header: 'Gender', key: 'gender' },
      { header: 'Status', key: 'status' },
      {
        header: 'Class',
        key: 'classLabel',
        render: (_value, item) => item.classLabel ?? '-',
      },
      {
        header: 'Stream',
        key: 'streamName',
        render: (_value, item) => item.streamName ?? '-',
      },
      {
        header: 'Guardian Name',
        key: 'guardian_name',
        render: (_value, item) => item.primary_guardian?.name || '-',
      },
      {
        header: 'Guardian Phone',
        key: 'guardian_phone',
        render: (_value, item) => item.primary_guardian?.phone || '-',
      },
    ],
    []
  );

  const isLoadingPage = loading || !scopeReady;
  const reportTitle = scope.year
    ? `${t('studentMasterlistPage.title')} · ${scope.year.name}`
    : t('studentMasterlistPage.title');
  const emptyState =
    (students ?? []).length === 0
      ? t(
          'studentMasterlistPage.noStudentsInYear',
          'No learners are on the roll for this school year.'
        )
      : t(
          'studentMasterlistPage.noStudentsForScope',
          'No learners match the selected year, class, stream, status and gender.'
        );

  const handlePrint = () => {
    window.print();
  };

  const handleExportCSV = () => {
    const headers = columns.map(col => col.header).join(',');
    const rows = (generatedStudents || []).map(student => {
      return columns.map(col => {
        let value;
        if (col.render) {
          value = col.render(student[col.key as keyof ReportStudent], student);
        } else {
          value = student[col.key as keyof ReportStudent] as string | number | undefined;
        }
        // Handle potential commas in values by double-quoting
        const stringValue = String(value !== undefined && value !== null ? value : '-');
        return `"${stringValue.replace(/"/g, '""')}"`; // Escape double quotes
      }).join(',');
    }).join('\n');

    const csvContent = `${headers}\n${rows}`;
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    if (link.download !== undefined) {
      const url = URL.createObjectURL(blob);
      const today = new Date().toISOString().split('T')[0];
      link.setAttribute('href', url);
      link.setAttribute('download', `student_masterlist_${today}.csv`);
      link.style.visibility = 'hidden';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
    }
  };

  return (
    <div className="space-y-3">
      <Card title={t('studentMasterlistPage.title')} info={t('studentMasterlistPage.filterDescription')}>
        <div className="p-4 border-b mb-4 bg-surface-muted rounded-md filter-section print:hidden">
          <AcademicScopeFilterBar scope={academicScope}>
            <Select
              label={t('studentMasterlistPage.filterByStatus')}
              value={selectedStatus}
              onChange={e => setSelectedStatus(e.target.value as StudentStatus | '')}
            >
              <option value="">{t('studentMasterlistPage.allStatuses')}</option>
              {Object.values(StudentStatus).map(s => <option key={s} value={s}>{s}</option>)}
            </Select>
            <Select
              label={t('studentMasterlistPage.filterByGender')}
              value={selectedGender}
              onChange={e => setSelectedGender(e.target.value as PersonGender | '')}
            >
              <option value="">{t('studentMasterlistPage.allGenders')}</option>
              {Object.values(PersonGender).map(g => <option key={g} value={g}>{g}</option>)}
            </Select>
            <Button
              onClick={generateReport}
              disabled={isLoadingPage}
              className="h-10"
            >
              {t('studentMasterlistPage.generateReport')}
            </Button>
          </AcademicScopeFilterBar>
        </div>

        {isLoadingPage || generatedStudents === null ? (
          <div className="flex justify-center items-center py-10">
            <Spinner size="lg" />
            <span className="ml-2">{t('studentMasterlistPage.loadingInitialData')}</span>
          </div>
        ) : (
          <>
            <div className="flex justify-end space-x-2 mb-4 print:hidden">
              <Button variant="secondary" size="sm" onClick={handlePrint}>
                {t('studentMasterlistPage.print')}
              </Button>
              <Button variant="secondary" size="sm" onClick={handleExportCSV}>
                {t('studentMasterlistPage.exportCSV')}
              </Button>
            </div>
            <SchoolLetterhead title={reportTitle} />
            <DataGrid
              columns={columns}
              data={generatedStudents}
              loading={false}
              emptyState={emptyState}
            />
          </>
        )}
      </Card>
    </div>
  );
};

const StudentMasterlistPage: React.FC = () => (
  <CanonicalRepositoryProvider>
    <div className="space-y-3">
      <StudentMasterlistPageContent />
    </div>
  </CanonicalRepositoryProvider>
);

export default StudentMasterlistPage;
