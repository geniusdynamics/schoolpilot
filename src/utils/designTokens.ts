// CSS custom property generator for theme switching
export const generateCSSCustomProperties = (tokens: DesignTokens, theme: 'light' | 'dark' = 'light'): Record<string, string> => {
  const properties: Record<string, string> = {};
  
  // Color properties
  Object.entries(tokens.colors).forEach(([colorName, colorValue]) => {
    if (typeof colorValue === 'object' && 'surface' in tokens.colors && colorName !== 'surface') {
      // Handle color scales
      Object.entries(colorValue as ColorScale).forEach(([shade, value]) => {
        properties[`--color-${colorName}-${shade}`] = value;
      });
    }
  });
  
  // Surface colors (theme-aware)
  const surfaceColors = theme === 'dark' ? {
    background: '#0f172a',
    foreground: '#f8fafc',
    card: '#1e293b',
    cardForeground: '#f8fafc',
    popover: '#1e293b',
    popoverForeground: '#f8fafc',
    muted: '#334155',
    mutedForeground: '#94a3b8',
    accent: '#334155',
    accentForeground: '#f8fafc',
    border: '#334155',
    input: '#334155',
    ring: '#3b82f6',
  } : tokens.colors.surface;
  
  Object.entries(surfaceColors).forEach(([key, value]) => {
    properties[`--color-${key}`] = value;
  });
  
  // Typography properties
  properties['--font-family-sans'] = tokens.typography.fontFamily.sans.join(', ');
  properties['--font-family-serif'] = tokens.typography.fontFamily.serif.join(', ');
  properties['--font-family-mono'] = tokens.typography.fontFamily.mono.join(', ');
  
  // Spacing properties
  Object.entries(tokens.spacing).forEach(([key, value]) => {
    properties[`--spacing-${key}`] = value;
  });
  
  // Border radius properties
  Object.entries(tokens.borderRadius).forEach(([key, value]) => {
    properties[`--border-radius-${key}`] = value;
  });
  
  // Shadow properties
  Object.entries(tokens.shadows).forEach(([key, value]) => {
    properties[`--shadow-${key}`] = value;
  });
  
  // Animation properties
  Object.entries(tokens.animations.duration).forEach(([key, value]) => {
    properties[`--duration-${key}`] = value;
  });
  
  Object.entries(tokens.animations.easing).forEach(([key, value]) => {
    properties[`--easing-${key}`] = value;
  });
  
  return properties;
};

// Helper function to apply CSS custom properties to document
export const applyCSSCustomProperties = (theme: 'light' | 'dark' = 'light'): void => {
  const properties = generateCSSCustomProperties(designTokens, theme);
  const root = document.documentElement;
  
  Object.entries(properties).forEach(([property, value]) => {
    root.style.setProperty(property, value);
  });
  
  // Set theme class for additional styling
  root.classList.remove('light', 'dark');
  root.classList.add(theme);
};